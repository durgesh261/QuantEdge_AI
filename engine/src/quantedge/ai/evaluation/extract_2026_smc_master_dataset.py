def extract_2026_master_dataset(
    canonical_base: Optional[Path] = None,
    repo_root: Optional[Path] = None,
    filter_by: str = "decision_or_creation",
) -> Tuple[List[MasterOrderBlockRecord], Dict[str, Any]]:
    """
    Extracts all 2026 qualifying SMC Order Blocks across BTCUSD, ETHUSD, SOLUSD, XRPUSD.
    """
    root = repo_root or _find_repo_root()
    if canonical_base is None:
        canonical_base = root / "data" / "canonical" / "delta_exchange_india"

    records: List[MasterOrderBlockRecord] = []
    symbol_counts: Dict[str, int] = {}
    direction_counts: Dict[str, int] = {"LONG": 0, "SHORT": 0}
    month_counts: Dict[str, int] = {}
    zone_sizes: List[float] = []

    for sym in CANONICAL_SYMBOLS:
        candles = load_canonical_full_history(canonical_base, sym)
        ctx = build_smc_context(candles)
        setups, _ = extract_phase_i_setups(candles, symbol=sym, ctx=ctx)

        sym_2026_count = 0
        for s in setups:
            dec_dt = datetime.fromisoformat(s.decision_time)
            cre_dt = datetime.fromisoformat(s.creation_time)

            if filter_by == "decision_only" and dec_dt < START_2026_UTC:
                continue
            elif filter_by == "creation_only" and cre_dt < START_2026_UTC:
                continue
            elif filter_by == "decision_or_creation" and (dec_dt < START_2026_UTC and cre_dt < START_2026_UTC):
                continue

            # Extract causal 29 features at decision bar
            feats_29 = extract_ob_causal_features(s, candles, ctx)
            feat_dict = {f"feat_{name}": round(float(v), 6) for name, v in zip(OB_FEATURE_NAMES, feats_29)}

            # Source candle info
            src_idx = s.formation_index if s.formation_index >= 0 else s.decision_bar
            src_candle = candles[src_idx]

            # Invalidation analysis across history
            inval_status = "NOT_INVALIDATED"
            inval_bar = -1
            inval_ts = ""
            for k in range(s.decision_bar + 1, len(candles)):
                c_k = candles[k]
                if s.direction == "LONG" and float(c_k.low) < s.ob_low:
                    inval_status = "INVALIDATED"
                    inval_bar = k
                    inval_ts = c_k.timestamp.isoformat()
                    break
                elif s.direction == "SHORT" and float(c_k.high) > s.ob_high:
                    inval_status = "INVALIDATED"
                    inval_bar = k
                    inval_ts = c_k.timestamp.isoformat()
                    break

            # Forward replay & touch outcome
            decision_obj = StrategyDecision(
                timestamp=datetime.fromisoformat(s.creation_time),
                symbol=s.asset,
                timeframe=s.timeframe,
                direction=StrategyDirection.LONG if s.direction == "LONG" else StrategyDirection.SHORT,
                setup_id=s.setup_id,
                entry=Decimal(str(s.entry_price)),
                stop_loss=Decimal(str(s.sl_price)),
                take_profit=Decimal(str(s.tp_price)),
                risk_distance=Decimal(str(s.risk_distance)),
            )
            outcome = replay_forward_outcome(
                setup_idx=s.decision_bar,
                candles=candles,
                decision=decision_obj,
                max_holding_bars=REPLAY_HORIZON_BARS,
            )
            if outcome is None:
                continue

            # First touch detection
            touch_occurred = False
            touch_bar = -1
            touch_ts = ""
            touch_px = 0.0
            max_scan = min(len(candles) - 1, s.decision_bar + REPLAY_HORIZON_BARS)

            for k in range(s.decision_bar + 1, max_scan + 1):
                c_k = candles[k]
                l_k = float(c_k.low)
                h_k = float(c_k.high)
                is_touch = (l_k <= s.ob_high and h_k >= s.ob_low)
                if is_touch:
                    touch_occurred = True
                    touch_bar = k
                    touch_ts = c_k.timestamp.isoformat()
                    touch_px = s.ob_high if s.direction == "LONG" else s.ob_low
                    break

            touch_res = "NO_TOUCH_EXPIRED"
            if inval_status == "INVALIDATED" and (not touch_occurred or inval_bar < touch_bar):
                touch_res = "NO_TOUCH_INVALIDATED"
            elif touch_occurred:
                if outcome.exit_reason == "TP_HIT":
                    touch_res = "TOUCH_HIT_TP"
                elif outcome.exit_reason == "SL_HIT":
                    touch_res = "TOUCH_HIT_SL"
                elif outcome.exit_reason == "TIMEOUT_72H":
                    touch_res = "TOUCH_TIMEOUT_72H"
                else:
                    touch_res = f"TOUCH_{outcome.exit_reason}"

            top_p = s.ob_high
            bot_p = s.ob_low
            z_size = abs(top_p - bot_p)
            z_size_pct = (z_size / bot_p * 100.0) if bot_p > 0 else 0.0
            z_mid = (top_p + bot_p) / 2.0
            atr_val = float(ctx.parsed[s.decision_bar].atr_value) if ctx.parsed[s.decision_bar].atr_value else (s.entry_price * 0.01)

            rec = MasterOrderBlockRecord(
                ob_id=s.setup_id,
                asset=sym,
                symbol=sym,
                direction=s.direction,
                timeframe="1h",
                creation_timestamp=s.creation_time,
                creation_bar_index=s.formation_index,
                confirmation_timestamp=s.confirmation_time,
                confirmation_bar_index=s.break_index,
                decision_timestamp=s.decision_time,
                decision_bar_index=s.decision_bar,
                top_price=round(top_p, 6),
                bottom_price=round(bot_p, 6),
                zone_size=round(z_size, 6),
                zone_size_percent=round(z_size_pct, 4),
                zone_midpoint=round(z_mid, 6),
                entry_price=round(s.entry_price, 6),
                sl_price=round(s.sl_price, 6),
                tp_price=round(s.tp_price, 6),
                risk_distance=round(s.risk_distance, 6),
                stop_distance_percent=round(s.stop_distance_percent, 4),
                atr_at_decision=round(atr_val, 6),
                atr_normalized_stop_distance=round(s.risk_distance / atr_val, 4) if atr_val > 0 else 0.0,
                leverage=s.leverage,
                source_candle_index=src_idx,
                source_candle_timestamp=src_candle.timestamp.isoformat(),
                source_candle_open=float(src_candle.open),
                source_candle_high=float(src_candle.high),
                source_candle_low=float(src_candle.low),
                source_candle_close=float(src_candle.close),
                source_candle_volume=float(src_candle.volume),
                break_type=s.structural_event_id.split("|")[1] if "|" in s.structural_event_id else "BOS",
                structure_origin=s.structure_origin,
                trend_before_break="BULLISH" if s.direction == "LONG" else "BEARISH",
                internal_trend_at_decision="BULLISH" if candles[s.decision_bar].close > candles[max(0, s.decision_bar - 5)].close else "BEARISH",
                swing_trend_at_decision="BULLISH" if candles[s.decision_bar].close > candles[max(0, s.decision_bar - 50)].close else "BEARISH",
                structural_event_id=s.structural_event_id,
                qualification_status=f"QUALIFIED_{s.direction}",
                invalidation_status=inval_status,
                invalidation_bar_index=inval_bar,
                invalidation_timestamp=inval_ts,
                first_touch_occurred=touch_occurred,
                first_touch_bar_index=touch_bar,
                first_touch_timestamp=touch_ts,
                first_touch_price=round(touch_px, 6),
                first_touch_result=touch_res,
                realized_r=round(outcome.realized_r, 4),
                holding_bars=outcome.holding_bars,
                mfe_r=round(outcome.mfe_r, 4),
                mae_r=round(outcome.mae_r, 4),
                feature_cutoff_timestamp=s.decision_time,
                **feat_dict,
            )

            records.append(rec)
            sym_2026_count += 1
            direction_counts[s.direction] += 1
            m_str = dec_dt.strftime("%Y-%m")
            month_counts[m_str] = month_counts.get(m_str, 0) + 1
            zone_sizes.append(z_size_pct)

        symbol_counts[sym] = sym_2026_count

    # Sort deterministically by decision timestamp and symbol
    records.sort(key=lambda r: (r.decision_timestamp, CANONICAL_SYMBOLS.index(r.asset)))

    stats = {
        "total_2026_obs": len(records),
        "symbol_counts": symbol_counts,
        "direction_counts": direction_counts,
        "month_counts": dict(sorted(month_counts.items())),
        "earliest_timestamp": records[0].decision_timestamp if records else "",
        "latest_timestamp": records[-1].decision_timestamp if records else "",
        "min_zone_size_pct": round(float(np.min(zone_sizes)), 4) if zone_sizes else 0.0,
        "max_zone_size_pct": round(float(np.max(zone_sizes)), 4) if zone_sizes else 0.0,
        "median_zone_size_pct": round(float(np.median(zone_sizes)), 4) if zone_sizes else 0.0,
        "mean_zone_size_pct": round(float(np.mean(zone_sizes)), 4) if zone_sizes else 0.0,
        "unique_ob_ids": len(set(r.ob_id for r in records)),
        "duplicate_count": len(records) - len(set(r.ob_id for r in records)),
        "invalidated_count": sum(1 for r in records if r.invalidation_status == "INVALIDATED"),
        "touched_count": sum(1 for r in records if r.first_touch_occurred),
    }

    return records, stats


def write_master_dataset_artifacts(
    records: List[MasterOrderBlockRecord],
    stats: Dict[str, Any],
    repo_root: Optional[Path] = None,
) -> Dict[str, Path]:
    """Writes CSV, JSON, and Markdown documentation artifacts."""
    root = repo_root or _find_repo_root()
    docs_dir = root / "docs" / "ai"
    docs_dir.mkdir(parents=True, exist_ok=True)

    csv_path = docs_dir / "2026_smc_order_blocks_master.csv"
    json_path = docs_dir / "2026_smc_order_blocks_master.json"
    doc_path = docs_dir / "2026_SMC_OB_MASTER_DATASET.md"

    # 1. Write CSV
    if records:
        fieldnames = list(asdict(records[0]).keys())
        with open(csv_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            for r in records:
                writer.writerow(asdict(r))

    # 2. Write JSON
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump([asdict(r) for r in records], f, indent=2)

    # 3. Write Documentation Markdown
    _write_markdown_documentation(doc_path, stats, records)

    return {
        "master_csv": csv_path,
        "master_json": json_path,
        "dataset_doc": doc_path,
    }


